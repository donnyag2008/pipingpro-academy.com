/* =============================================================================
 * TOLERANCES — ASME B16.10-2000 §5
 * ===========================================================================*/
const B16_10_TOLERANCE = {
  // Straightway valves (§5.1)
  straightway: {
    small: { maxNPS: 10, mm: 2, in: 0.06 },   // NPS 10 (DN 250) and smaller
    large: { minNPS: 12, mm: 3, in: 0.12 }    // NPS 12 (DN 300) and larger
  },
  // Angle valves (§5.2) — one-half the straightway value
  angleFactor: 0.5
};

function b1610Tolerance(nps, type = "straightway", units = "mm") {
  const t = B16_10_TOLERANCE.straightway;
  let base = nps <= t.small.maxNPS ? t.small[units] : t.large[units];
  if (type === "angle") base *= B16_10_TOLERANCE.angleFactor;
  return base; // ± value
}


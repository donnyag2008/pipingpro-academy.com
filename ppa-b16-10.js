/* Look up the ring-joint X adjustment. Returns X (number) or null. */
function getRtjX(cls, nps, units = "mm") {
  const tbl = B16_10_RTJ_X?.[cls];
  if (!tbl) return null;
  const r = tbl.find(x => x[0] === nps);
  if (!r) return null;                 // size omitted / not tabulated → caller must verify
  return units === "mm" ? r[2] : r[3];
}

/* Ring-joint end-to-end = RF face-to-face + X  (angle valves: + X/2).
 * Returns null if either the RF face-to-face or X is unavailable. */
function getRtjEndToEnd({ cls, family, nps, units = "mm" }) {
  const isAngle = family === "angle";
  const ff = getValveLength({ cls, family, nps, dim: "ff", pattern: "long", units });
  const x  = getRtjX(cls, nps, units);
  if (ff == null || x == null) return null;
  return ff + (isAngle ? x / 2 : x);
}

/* =============================================================================
 * LOOKUP HELPER
 * -----------------------------------------------------------------------------
 *   getValveLength({ cls, family, nps, dim, pattern, units })
 *     cls     : "150" | "300" | "600" | "900" | "1500" | "2500" | "CI125" | "CI250"
 *     family  : "gate" | "globeCheck" | "swingCheck" | "ball" | "plug" | "angle"
 *     nps     : numeric NPS (e.g. 6, 0.5, 1.5)
 *     dim     : "ff" (face-to-face, flanged RF) | "ete" (buttwelding end-to-end)
 *     pattern : "long" (default) | "short"
 *     units   : "mm" (default) | "in"
 *   Returns the dimension (number) or null if not tabulated.
 * ===========================================================================*/
function getValveLength({ cls, family, nps, dim = "ff", pattern = "long", units = "mm" }) {
  const node = B16_10?.[cls]?.[family];
  if (!node) return null;

  if (pattern === "short" && node.short) {
    const r = node.short.find(x => x[0] === nps);
    if (!r) return null;
    return units === "mm" ? r[2] : r[3];   // short rows: [nps, dn, mm, in]
  }

  const r = node.rows.find(x => x[0] === nps);
  if (!r) return null;
  // rows: [nps, dn, ff_mm, ete_mm, ff_in, ete_in]
  if (units === "mm") return dim === "ete" ? r[3] : r[2];
  return dim === "ete" ? r[5] : r[4];
}

/* Apply a facing adjustment to a tabulated RF face-to-face value. */
function applyFacingAdj(value, cls, facing, units = "mm", isAngle = false) {
  if (value == null) return null;
  const group = (cls === "600" || cls === "900" || cls === "1500" || cls === "2500")
    ? "raised7mm"
    : (cls === "150" || cls === "300" || cls === "CI250") ? "raised2mm" : null;
  if (!group) return value;            // flat face / CI125 → no delta
  const adj = B16_10_FACING_ADJ[group]?.[facing];
  if (!adj) return value;              // RF or unknown facing
  let d = adj[units] || 0;
  if (isAngle) d *= 0.5;               // angle valves: half the delta
  return value + d;
}


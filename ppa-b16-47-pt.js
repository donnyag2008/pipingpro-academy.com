  /* ---- convenience: interpolate B16.47 rating ---- */
  function pt47Rating(group, cls, tempF) {
    const r = PT47_RATINGS[group];
    if (!r) return null;
    const pArr = r[String(cls)];
    if (!pArr) return null;
    /* filter out null entries (Class 75/150 stop at lower temps) */
    const validT = [], validP = [];
    for (let i = 0; i < r.t.length; i++) {
      if (i < pArr.length && pArr[i] !== null) {
        validT.push(r.t[i]);
        validP.push(pArr[i]);
      }
    }
    if (validT.length === 0) return null;
    const interp = (g.PPA && g.PPA.interp) ? g.PPA.interp : function(arr, ts, x) {
      if (x <= ts[0])              return { v: arr[0], clamp: x < ts[0] ? 'low' : null };
      if (x >= ts[ts.length - 1])  return { v: arr[arr.length - 1], clamp: x > ts[ts.length - 1] ? 'high' : null };
      for (let i = 0; i < ts.length - 1; i++) {
        if (x >= ts[i] && x <= ts[i + 1]) {
          const f = (x - ts[i]) / (ts[i + 1] - ts[i]);
          return { v: arr[i] + f * (arr[i + 1] - arr[i]), clamp: null };
        }
      }
      return { v: arr[0], clamp: null };
    };
    return interp(validP, validT, tempF);
  }

